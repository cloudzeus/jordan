// Η σειρά μετρά: πιο ειδικό πρώτο (η «κόλλα πλακιδίων» είναι κόλλα, όχι πλακάκι).
const RULES: [GuideProfileKey, RegExp][] = [
  ['adhesives', /κολλ|κονιαμ|αρμοστοκ|αρμοκ|grout|adhesive|στοκος|τσιμεντοκονι|c2te|c1te/],
  ['electrical', /ηλεκτρ|φωτιστ|λαμπ|led|καλωδ|πριζ|διακοπτ|φως/],
  ['plumbing', /υδραυλ|μπαταρ|νιπτηρ|λεκαν|ντουζ|σιφων|βρυση|υγιειν|μπανιερ|καζανακ/],
  ['tiles', /πλακακ|πλακιδ|tile|porcel|gres|zellige|bejmat|terrazzo|ψηφιδ|mosaic|κεραμικ/],
  ['stone', /πετρ|μαρμαρ|γρανιτ|stone|marble|σχιστολ|travertin/],
  ['flooring', /laminate|παρκε|δαπεδ|βινυλ|spc|lvt|σανιδ/],
  ['paint', /χρωμ|βαφ|σοβα|επιχρισ|ασταρ|βερνικ|paint/],
  ['drywall', /γυψοσαν|ψευδοροφ|drywall|knauf|γυψ/],
  ['joinery', /κουφωμ|πορτ|παραθυρ|αλουμιν|πατζουρ|ξυλουργ/],
  ['furniture', /επιπλ|ντουλαπ|κουζιν|ραφι|πάγκ|παγκ|συρταρ/],
];

/** Πεζά χωρίς τόνους — οι κανόνες γράφονται μία φορά. */
export const fold = (s: string) => s.toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '');

export function guideProfile(input: { category?: string | null; group?: string | null; name: string; isService: boolean }): GuideProfile {
  if (input.isService) return { key: 'service', ...P.service };
  // Η περιγραφή πρώτα (η πιο ειδική: μια «κόλλα» μπορεί να ζει στην ομάδα «Πλακάκια»),
  // μετά η ομάδα, τελευταία η (γενική) εμπορική κατηγορία.
  for (const text of [input.name, input.group, input.category]) {
    if (!text) continue;
    const t = fold(text);
    const hit = RULES.find(([, re]) => re.test(t));
    if (hit) return { key: hit[0], ...P[hit[0]] };
  }
  return { key: 'general', ...P.general };
}

export const profileLabel = (key: string) => (P as Record<string, { label: string } | undefined>)[key]?.label ?? P.general.label;
