/** Οδηγίες φροντίδας για όσα υλικά υπάρχουν στο έργο (κάθε οδηγός μία φορά, με σταθερή σειρά). */
export function careGuides(materialNames: string[]): CareGuide[] {
  // Χωρίς τόνους και πεζά, ώστε να πιάνει «ΠΛΑΚΙΔΙΩΝ», «πλακίδια», «Πλακάκι» κ.λπ.
  const text = materialNames.join(' \n ').normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase();
  return GUIDES.filter((g) => g.match.test(text)).map(({ match: _m, ...g }) => g);
}

export type DossierMaterial = { code: string | null; name: string; qty: number; unit: string | null; room: string | null };

/** Υλικά ομαδοποιημένα ανά χώρο (σειρά της κάτοψης· «Γενικά» στο τέλος), ίδιο είδος ενωμένο. */
export function materialsByRoom(lines: DossierMaterial[], roomOrder: string[]): { room: string; items: DossierMaterial[] }[] {
  const by = new Map<string, Map<string, DossierMaterial>>();
  for (const l of lines) {
    const room = l.room ?? 'Γενικά';
    const m = by.get(room) ?? new Map<string, DossierMaterial>();
    const key = `${l.code ?? ''}|${l.name}|${l.unit ?? ''}`;
    const cur = m.get(key);
    if (cur) cur.qty = Math.round((cur.qty + l.qty) * 1000) / 1000; else m.set(key, { ...l, room });
    by.set(room, m);
  }
  const order = [...roomOrder.filter((r) => by.has(r)), ...[...by.keys()].filter((r) => !roomOrder.includes(r) && r !== 'Γενικά'), ...(by.has('Γενικά') ? ['Γενικά'] : [])];
  return order.map((room) => ({ room, items: [...by.get(room)!.values()] }));
}
